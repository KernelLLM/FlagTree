@host
def launch(
    self,
    gm_output,
    gm_query,
    gm_key_cache,
    gm_value_cache,
    gm_block_table,
    gm_query_dequant_scale,
    gm_value_dequant_scale,
    gm_core_task_ranges,
    gm_query_sequence_boundaries,
    gm_key_value_lengths,
    gm_nz_gather_indices,
    batch: int,
    n_q_heads: int,
    head_group: int,
    block_dim: int,
    gm_log_quant_scale_p: Tensor,
):
    op = FlashAttnFp8FullQuantKernel(
        self.m_base_size,
        self.s2_base_size,
        self.d,
        self.block_size,
        self.depths,
        self.mask_tail,
        self.layout,
    )
    op[block_dim](
        gm_query,
        gm_key_cache,
        gm_value_cache,
        gm_block_table,
        gm_query_dequant_scale,
        gm_value_dequant_scale,
        gm_core_task_ranges,
        gm_query_sequence_boundaries,
        gm_key_value_lengths,
        gm_nz_gather_indices,
        gm_output,
        batch,
        n_q_heads,
        head_group,
        gm_log_quant_scale_p,
    )
